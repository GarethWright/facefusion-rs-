    // --- PSNR -----------------------------------------------------------
    //
    // skimage was not importable in this environment (`python3 -c "import skimage"` raised
    // ModuleNotFoundError), so PSNR is verified against hand-computed values instead of a
    // live skimage/scipy run.

    [Fact]
    public void Psnr_IdenticalArrays_IsPositiveInfinity()
    {
        var a = new double[] { 1, 2, 3, 4, 5 };
        Assert.Equal(double.PositiveInfinity, ImageMetrics.Psnr(a, a));
    }

    [Fact]
    public void Psnr_HandComputedValue_MatchesFormula()
    {
        // By hand: actual all 0, expected all 10 -> mse = 100, psnr = 10*log10(255^2/100)
        // = 10*log10(650.25) = 28.13080360867910... (computed with numpy for the digits).
        var actual = new double[] { 0, 0, 0, 0 };
        var expected = new double[] { 10, 10, 10, 10 };

        var psnr = ImageMetrics.Psnr(actual, expected);

        Assert.Equal(28.130803608679106, psnr, 9);
    }

    [Fact]
    public void Psnr_SimpleTwoElementCase_MatchesHandCalculation()
    {
        // actual=[0,10], expected=[0,0] -> mse = (0+100)/2 = 50
        // psnr = 10*log10(255^2/50) = 10*log10(1300.5) = 31.1401... (hand + calculator check)
        var actual = new double[] { 0, 10 };
        var expected = new double[] { 0, 0 };

        var psnr = ImageMetrics.Psnr(actual, expected);
        var expectedPsnr = 10.0 * Math.Log10(255.0 * 255.0 / 50.0);

        Assert.Equal(expectedPsnr, psnr, 9);
    }

    [Fact]
    public void Psnr_EmptyArrays_Throws()
    {
        Assert.Throws<ArgumentException>(() => ImageMetrics.Psnr(ReadOnlySpan<double>.Empty, ReadOnlySpan<double>.Empty));
    }

    [Fact]
    public void Psnr_SizeMismatch_Throws()
    {
        Assert.Throws<ArgumentException>(() => ImageMetrics.Psnr(new double[] { 1, 2 }, new double[] { 1, 2, 3 }));
    }

    // --- SSIM -------------------------------------------------------------
    //
    // skimage was not importable here, so exact skimage cross-checking wasn't possible.
    // Instead these tests check:
    //  (1) SSIM(x, x) == 1 (mathematical identity of the formula, independent of variant), and
    //  (2) agreement with an independently-written Python/numpy implementation of the same
    //      Gaussian-weighted, valid-convolution, population-covariance SSIM formula described
    //      in ImageMetrics.Ssim's doc comment (not copy-pasted from the C# code - written
    //      separately from the Wang et al. paper - see the report for the reference script).

    [Fact]
    public void Ssim_IdenticalImages_IsOne()
    {
        var rng = new Random(7);
        var image = new double[15 * 16];
        for (var i = 0; i < image.Length; i++)
        {
            image[i] = rng.NextDouble() * 255.0;
        }

        var ssim = ImageMetrics.Ssim(image, image, width: 16, height: 15);
        Assert.Equal(1.0, ssim, 9);
    }

    [Fact]
    public void Ssim_NoisyImage_MatchesIndependentPythonReference()
    {
        var img1 = ParseCsv(Image1Csv);
        var img2 = ParseCsv(Image2Csv);

        // Independent numpy reference (see report) computed 0.9985011937142496 for this pair
        // at width=16, height=15.
        var ssim = ImageMetrics.Ssim(img1, img2, width: 16, height: 15);

        Assert.Equal(0.9985011937142496, ssim, 6);
    }

    [Fact]
    public void Ssim_EmptyInput_Throws()
    {
        Assert.Throws<ArgumentException>(() => ImageMetrics.Ssim(ReadOnlySpan<double>.Empty, ReadOnlySpan<double>.Empty, width: 0, height: 0));
    }

    [Fact]
    public void Ssim_SizeMismatch_Throws()
    {
        var a = new double[11 * 11];
        var b = new double[11 * 12];
        Assert.Throws<ArgumentException>(() => ImageMetrics.Ssim(a, b, width: 11, height: 11));
    }

    [Fact]
    public void Ssim_ImageSmallerThanWindow_Throws()
    {
        // 11x11 is the window size; 10x10 must be rejected as too small.
        var a = new double[10 * 10];
        var b = new double[10 * 10];
        Assert.Throws<ArgumentException>(() => ImageMetrics.Ssim(a, b, width: 10, height: 10));
    }

    [Fact]
    public void Ssim_ImageExactlyWindowSize_Succeeds()
    {
        var rng = new Random(11);
        var a = new double[11 * 11];
        for (var i = 0; i < a.Length; i++)
        {
            a[i] = rng.NextDouble() * 255.0;
        }

        var ssim = ImageMetrics.Ssim(a, a, width: 11, height: 11);
        Assert.Equal(1.0, ssim, 9);
    }

    private static double[] ParseCsv(string csv)
    {
        var parts = csv.Split(',', StringSplitOptions.RemoveEmptyEntries);
        var result = new double[parts.Length];
        for (var i = 0; i < parts.Length; i++)
        {
            result[i] = double.Parse(parts[i], CultureInfo.InvariantCulture);
        }

        return result;
    }

