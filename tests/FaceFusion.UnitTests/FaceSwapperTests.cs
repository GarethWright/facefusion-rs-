    [Fact]
    public void BalanceSourceEmbeddingAtWeightZeroFiveIsPureSourceNotTheMidpoint()
    {
        // Python: interp(0.5, [0,1], [0.35,-0.35]) == 0.0 exactly (the midpoint of the
        // *effective* weight range, not of the [0,1] UI slider) -> the target's contribution
        // is multiplied by 0, so face_swapper_weight = 0.5 is pure source identity, not a
        // source/target midpoint blend. Counterintuitive; reproduced exactly, not "fixed".
        var source = new[] { 1f, 2f, 3f };
        var target = new[] { 3f, 2f, 1f };

        var result = FaceSwapper.BalanceSourceEmbedding(FaceSwapperModelKind.Ghost, source, target, faceSwapperWeight: 0.5);

        AssertClose(1.0, result[0]);
        AssertClose(2.0, result[1]);
        AssertClose(3.0, result[2]);
    }

    [Fact]
    public void BalanceSourceEmbeddingAtWeightZeroIsPureSource()
    {
        // Python: interp(0, [0,1], [0.35,-0.35]) == 0.35 (not 0!) — weight=0 does NOT mean
        // "100% source", it means a 0.35 blend toward source. Reproduced exactly, not "fixed".
        var source = new[] { 1f, 0f };
        var target = new[] { 0f, 1f };

        var result = FaceSwapper.BalanceSourceEmbedding(FaceSwapperModelKind.Ghost, source, target, faceSwapperWeight: 0.0);

        // result = source*(1-0.35) + target*0.35 = source*0.65 + target*0.35
        AssertClose((1.0 * 0.65) + (0.0 * 0.35), result[0]);
        AssertClose((0.0 * 0.65) + (1.0 * 0.35), result[1]);
    }

    [Fact]
    public void BalanceSourceEmbeddingRenormalizesTargetForInswapperButNotForGhost()
    {
        var source = new[] { 0f, 0f };
        var target = new[] { 3f, 4f }; // norm = 5

        var ghostResult = FaceSwapper.BalanceSourceEmbedding(FaceSwapperModelKind.Ghost, source, target, faceSwapperWeight: 1.0);
        var inswapperResult = FaceSwapper.BalanceSourceEmbedding(FaceSwapperModelKind.Inswapper, source, target, faceSwapperWeight: 1.0);

        // weight=1 -> interp = -0.35, i.e. result = source*1.35 + target*(-0.35) = -0.35*target
        // (source is all-zero here, so result is entirely the (possibly renormalized) target term).
        AssertClose(-0.35 * 3.0, ghostResult[0]); // raw target, not renormalized
        AssertClose(-0.35 * 4.0, ghostResult[1]);

        AssertClose(-0.35 * (3.0 / 5.0), inswapperResult[0]); // target / ||target||
        AssertClose(-0.35 * (4.0 / 5.0), inswapperResult[1]);
    }

