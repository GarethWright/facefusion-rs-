    [Fact]
    public void NormalizeCropFrameForInswapperStaysFloat32AndSkipsRenormalize()
    {
        // 1x1 CHW: R=0.6, G=0.4, B=0.2 (already in [0,1], as a real model output would be).
        var chw = new[] { 0.6f, 0.4f, 0.2f };
        var mean = new[] { 0f, 0f, 0f };
        var std = new[] { 1f, 1f, 1f };

        using var result = FaceSwapper.NormalizeCropFrame(chw, height: 1, width: 1, FaceSwapperModelKind.Inswapper, mean, std);

        Assert.Equal(MatType.CV_32FC3, result.Type());
        var pixel = result.At<Vec3f>(0, 0);
        AssertClose(0.2 * 255, pixel.Item0); // B
        AssertClose(0.4 * 255, pixel.Item1); // G
        AssertClose(0.6 * 255, pixel.Item2); // R
    }

    [Fact]
    public void NormalizeCropFrameForGhostPromotesToFloat64AndRenormalizes()
    {
        var chw = new[] { 0.2f, 0.2f, 0.2f }; // R, G, B channel planes (1x1 each)
        var mean = new[] { 0.5f, 0.5f, 0.5f };
        var std = new[] { 0.5f, 0.5f, 0.5f };

        using var result = FaceSwapper.NormalizeCropFrame(chw, height: 1, width: 1, FaceSwapperModelKind.Ghost, mean, std);

        Assert.Equal(MatType.CV_64FC3, result.Type());
        // value = 0.2 * 0.5 + 0.5 = 0.6, clip(0,1) is a no-op, * 255 = 153
        var pixel = result.At<Vec3d>(0, 0);
        AssertClose(0.6 * 255, pixel.Item0);
        AssertClose(0.6 * 255, pixel.Item1);
        AssertClose(0.6 * 255, pixel.Item2);
    }

    [Fact]
    public void NormalizeCropFrameClipsBeforeRenormalizeRangeExceeded()
    {
        // A model output that, after renormalize, would exceed [0,1] must clip to it before
        // the *255, matching Python's `.clip(0, 1)` — not clip the final *255 result.
        var chw = new[] { 2.0f, -2.0f, 0.5f };
        var mean = new[] { 0.5f, 0.5f, 0.5f };
        var std = new[] { 0.5f, 0.5f, 0.5f };

        using var result = FaceSwapper.NormalizeCropFrame(chw, height: 1, width: 1, FaceSwapperModelKind.Uniface, mean, std);

        var pixel = result.At<Vec3d>(0, 0);
        // R: 2.0*0.5+0.5 = 1.5 -> clip -> 1.0 -> *255 = 255 (channel R lands at Item2, BGR)
        AssertClose(255.0, pixel.Item2);
        // G: -2.0*0.5+0.5 = -0.5 -> clip -> 0.0 -> *255 = 0
        AssertClose(0.0, pixel.Item1);
    }

