    [Fact]
    public void PrepareCropFrameReversesChannelsAndNormalizes()
    {
        using var crop = new Mat(1, 1, MatType.CV_8UC3);
        crop.Set(0, 0, new Vec3b(10, 20, 30)); // B=10, G=20, R=30

        var mean = new[] { 0.5f, 0.5f, 0.5f };
        var std = new[] { 0.5f, 0.5f, 0.5f };

        var chw = FaceSwapper.PrepareCropFrame(crop, mean, std);

        Assert.Equal(3, chw.Length);
        AssertClose(((30 / 255.0) - 0.5) / 0.5, chw[0]); // R -> channel 0
        AssertClose(((20 / 255.0) - 0.5) / 0.5, chw[1]); // G -> channel 1
        AssertClose(((10 / 255.0) - 0.5) / 0.5, chw[2]); // B -> channel 2
    }

    [Fact]
    public void PrepareCropFrameWithZeroMeanUnitStdIsJustNormalizedChannelReversal()
    {
        using var crop = new Mat(1, 1, MatType.CV_8UC3);
        crop.Set(0, 0, new Vec3b(0, 128, 255));

        var mean = new[] { 0f, 0f, 0f };
        var std = new[] { 1f, 1f, 1f };

        var chw = FaceSwapper.PrepareCropFrame(crop, mean, std);

        AssertClose(255 / 255.0, chw[0]);
        AssertClose(128 / 255.0, chw[1]);
        AssertClose(0 / 255.0, chw[2]);
    }

