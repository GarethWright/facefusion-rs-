    /// <summary>
    /// Ground truth from a live Python session (numpy 2.4.6):
    /// <code>
    /// img = numpy.arange(4*4*3).reshape(4,4,3).astype(numpy.uint8)
    /// implode_pixel_boost(img, 2, (2,2))[:, :, :, 0]
    /// # sub-image 0 (channel 0): [[0, 6], [24, 30]]
    /// # sub-image 1 (channel 0): [[3, 9], [27, 33]]
    /// # sub-image 2 (channel 0): [[12, 18], [36, 42]]
    /// # sub-image 3 (channel 0): [[15, 21], [39, 45]]
    /// explode_pixel_boost(list(sub_images), 2, (2,2), (4,4)) == img  # True
    /// </code>
    /// Confirms <see cref="PixelBoost.ImplodePixelBoost"/> is a strided "pixel unshuffle", not a
    /// coarse block tiling — see the class remarks in <c>PixelBoost.cs</c>.
    /// </summary>
    [Fact]
    public void ImplodePixelBoostMatchesPythonStridedUnshuffle()
    {
        using var image = new Mat(4, 4, MatType.CV_8UC3);
        var value = 0;
        for (var row = 0; row < 4; row++)
        {
            for (var col = 0; col < 4; col++)
            {
                image.Set(row, col, new Vec3b((byte)value, (byte)(value + 1), (byte)(value + 2)));
                value += 3;
            }
        }

        var subImages = PixelBoost.ImplodePixelBoost(image, pixelBoostTotal: 2, modelSize: new Size(2, 2));

        try
        {
            Assert.Equal(4, subImages.Count);

            AssertChannel0(subImages[0], new byte[,] { { 0, 6 }, { 24, 30 } });
            AssertChannel0(subImages[1], new byte[,] { { 3, 9 }, { 27, 33 } });
            AssertChannel0(subImages[2], new byte[,] { { 12, 18 }, { 36, 42 } });
            AssertChannel0(subImages[3], new byte[,] { { 15, 21 }, { 39, 45 } });
        }
        finally
        {
            foreach (var subImage in subImages)
            {
                subImage.Dispose();
            }
        }
    }

    private static void AssertChannel0(Mat subImage, byte[,] expected)
    {
        for (var row = 0; row < 2; row++)
        {
            for (var col = 0; col < 2; col++)
            {
                Assert.Equal(expected[row, col], subImage.At<Vec3b>(row, col).Item0);
            }
        }
    }

    [Fact]
    public void ExplodePixelBoostIsTheExactInverseOfImplode()
    {
        using var image = new Mat(4, 4, MatType.CV_8UC3);
        var random = new Random(42);
        for (var row = 0; row < 4; row++)
        {
            for (var col = 0; col < 4; col++)
            {
                image.Set(row, col, new Vec3b((byte)random.Next(256), (byte)random.Next(256), (byte)random.Next(256)));
            }
        }

        var subImages = PixelBoost.ImplodePixelBoost(image, pixelBoostTotal: 2, modelSize: new Size(2, 2));
        using var reconstructed = PixelBoost.ExplodePixelBoost(subImages, pixelBoostTotal: 2, modelSize: new Size(2, 2), pixelBoostSize: new Size(4, 4));

        foreach (var subImage in subImages)
        {
            subImage.Dispose();
        }

        for (var row = 0; row < 4; row++)
        {
            for (var col = 0; col < 4; col++)
            {
                Assert.Equal(image.At<Vec3b>(row, col), reconstructed.At<Vec3b>(row, col));
            }
        }
    }

    [Fact]
    public void PixelBoostTotalOneIsTheIdentity()
    {
        using var image = new Mat(4, 4, MatType.CV_8UC3, new Scalar(10, 20, 30));

        var subImages = PixelBoost.ImplodePixelBoost(image, pixelBoostTotal: 1, modelSize: new Size(4, 4));
        try
        {
            Assert.Single(subImages);
            for (var row = 0; row < 4; row++)
            {
                for (var col = 0; col < 4; col++)
                {
                    Assert.Equal(image.At<Vec3b>(row, col), subImages[0].At<Vec3b>(row, col));
                }
            }
        }
        finally
        {
            foreach (var subImage in subImages)
            {
                subImage.Dispose();
            }
        }
    }

